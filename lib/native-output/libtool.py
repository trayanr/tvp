import re

from common import files, invocation, preserving_times

root, config = invocation()
for path in files(root, config["paths"]):
    if path.suffix != ".la":
        continue
    contents = path.read_bytes()
    # Libtool's tag and exact empty old_library assignment, never shell eval.
    if not re.search(rb"^# Generated by .*libtool", contents, re.M):
        continue
    old = re.findall(rb"^old_library=(.*)$", contents, re.M)
    if old not in ([b"''"], [b'""']):
        continue
    cleaned = re.sub(rb"^dependency_libs='[^'\n]+'", b"dependency_libs='' #pruned", contents, flags=re.M)
    if cleaned != contents:
        def rewrite():
            with path.open("r+b") as stream:
                stream.write(cleaned)
                stream.truncate()
        preserving_times(path, rewrite)
